function selectShard(suites, shard = '1/1') {
  const match = /^([1-9]\d*)\/([1-9]\d*)$/.exec(shard);
  if (!match) throw new Error('Shard must be INDEX/TOTAL, using positive integers');
  const index = Number(match[1]), total = Number(match[2]);
  if (!Number.isSafeInteger(index) || !Number.isSafeInteger(total) || index > total || total > suites.length) {
    throw new Error('Shard index must be within total, and total must not exceed suite count');
  }
  return suites.filter((_, i) => i % total === index - 1);
}
